#!/usr/bin/env python3
"""
mt5_runner.py — compile + MT5 Strategy Tester (real ticks) from the command line.
Works on Windows (native) or Linux/macOS + Wine. Uses a DEDICATED PORTABLE terminal folder.

Safety rules built in:
  * never writes Login/Password/Server (no credentials); [Experts] AllowLiveTrading=0, AllowDllImport=0
  * UseCloud=0, UseRemote=0 (local agents only)
  * only the process this script starts is ever terminated (on timeout); other terminals are never killed;
    if the target portable terminal already runs, the script refuses to start
  * --dry-run prints/writes the files and commands without starting anything

Examples
  python mt5_runner.py compile  --terminal-dir "C:/MT5_research" --dry-run
  python mt5_runner.py backtest --terminal-dir ~/.wine/drive_c/MT5_research --wine wine \
         --symbol XAUUSD --preset ../../MQL5/Presets/XAU_300_Research_v1_safe1.set \
         --from 2025.10.31 --to 2026.10.31 --timeout 5400
  python mt5_runner.py parse    --report path/to/report.htm --json out.json
"""
import argparse, json, os, platform, shutil, subprocess, sys, time, datetime as dt

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
EA_NAME = "XAU_300_Research_v1"
EA_SRC = os.path.join(REPO, "MQL5", "Experts", EA_NAME + ".mq5")
EA_SUBDIR = "XAU300"           # EA is installed to <terminal>/MQL5/Experts/XAU300/
VALID_MODELS = {4: "Every tick based on real ticks"}


class RunnerError(Exception):
    pass


# ----------------------------------------------------------------------------- paths / process
def to_win_path(p, use_wine):
    """Path as seen by the Windows program. Under Wine use `winepath -w` when available."""
    if not use_wine:
        return os.path.abspath(p)
    p = os.path.abspath(p)
    wp = shutil.which("winepath")
    if wp:
        try:
            return subprocess.check_output([wp, "-w", p], text=True, stderr=subprocess.DEVNULL).strip()
        except Exception:
            pass
    return "Z:" + p.replace("/", "\\")


def exe_cmd(exe, args, wine):
    return ([wine, exe] if wine else [exe]) + args


def terminal_running(terminal_dir):
    """Best effort: is a terminal64.exe from THIS folder already running? (never kills anything)"""
    target = os.path.abspath(terminal_dir).lower()
    if os.name == "nt":
        try:
            out = subprocess.check_output(["powershell", "-NoProfile", "-Command",
                                           "Get-CimInstance Win32_Process -Filter \"Name='terminal64.exe'\" | ForEach-Object { $_.ExecutablePath }"],
                                          text=True, stderr=subprocess.DEVNULL)
            return any(target.replace("/", "\\") in l.strip().lower() for l in out.splitlines() if l.strip())
        except Exception:
            return False
    found = False
    for pid in os.listdir("/proc") if os.path.isdir("/proc") else []:
        if not pid.isdigit():
            continue
        try:
            cmd = open(f"/proc/{pid}/cmdline", "rb").read().replace(b"\0", b" ").decode("utf-8", "ignore").lower()
        except Exception:
            continue
        if "terminal64.exe" in cmd and (target in cmd or target.replace("/", "\\") in cmd):
            found = True
    return found


# ----------------------------------------------------------------------------- ini / preset
def read_set(path):
    """Read a .set file (UTF-16 or UTF-8). Returns ordered list of (key, value)."""
    with open(path, "rb") as fh:
        raw = fh.read()
    txt = raw.decode("utf-16") if raw[:2] in (b"\xff\xfe", b"\xfe\xff") else raw.decode("utf-8-sig")
    items = []
    for line in txt.splitlines():
        line = line.strip()
        if not line or line.startswith(";") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        items.append((k.strip(), v.split("||")[0].strip()))
    return items


def check_preset_safety(items):
    d = dict(items)
    if d.get("InpAllowRealAccount", "false").lower() not in ("false", "0"):
        raise RunnerError("preset sets InpAllowRealAccount=true; the runner only runs research presets")
    return d


def build_ini(a, set_name, report_rel):
    lines = [
        "; generated by mt5_runner.py — no credentials on purpose",
        "[Experts]",
        "AllowLiveTrading=0",
        "AllowDllImport=0",
        "Enabled=1",
        "",
        "[Tester]",
        f"Expert={EA_SUBDIR}\\{EA_NAME}",
        f"ExpertParameters={set_name}",
        f"Symbol={a.symbol}",
        f"Period={a.period}",
        f"Model={a.model}",
        f"ExecutionMode={a.execution_mode}",
        "Optimization=0",
        f"FromDate={a.date_from}",
        f"ToDate={a.date_to}",
        "ForwardMode=0",
        f"Deposit={a.deposit:g}",
        f"Currency={a.currency}",
        f"Leverage={a.leverage}",
        "ProfitInPips=0",
        f"Report={report_rel}",
        "ReplaceReport=1",
        "ShutdownTerminal=1",
        "UseLocal=1",
        "UseRemote=0",
        "UseCloud=0",
        "Visual=0",
        "",
    ]
    return "\r\n".join(lines)


def validate_args(a):
    if a.model not in VALID_MODELS and not a.allow_non_real_ticks:
        raise RunnerError(f"Model={a.model} is not real ticks (4). Pass --allow-non-real-ticks only for diagnostics.")
    for d in (a.date_from, a.date_to):
        dt.datetime.strptime(d, "%Y.%m.%d")
    if not a.leverage.startswith("1:"):
        raise RunnerError("--leverage must look like 1:500")


# ----------------------------------------------------------------------------- commands
def cmd_compile(a):
    term = os.path.abspath(a.terminal_dir)
    editor = os.path.join(term, "MetaEditor64.exe")
    dst_dir = os.path.join(term, "MQL5", "Experts", EA_SUBDIR)
    dst = os.path.join(dst_dir, EA_NAME + ".mq5")
    log = os.path.join(dst_dir, EA_NAME + ".compile.log")
    cmd = exe_cmd(editor, ["/portable", f"/compile:{to_win_path(dst, bool(a.wine))}",
                           f"/inc:{to_win_path(os.path.join(term, 'MQL5'), bool(a.wine))}",
                           f"/log:{to_win_path(log, bool(a.wine))}"], a.wine)
    plan = {"copy": [EA_SRC, dst], "command": cmd, "log": log}
    if a.dry_run:
        print(json.dumps({"dry_run": True, "compile": plan}, indent=1)); return 0
    if not os.path.isfile(editor):
        raise RunnerError(f"MetaEditor64.exe not found in {term}")
    os.makedirs(dst_dir, exist_ok=True); shutil.copy2(EA_SRC, dst)
    subprocess.run(cmd, timeout=a.timeout, check=False)   # MetaEditor's exit code is not reliable; read the log
    ok, summary = parse_compile_log(log)
    print(summary)
    return 0 if ok else 2


def parse_compile_log(path):
    if not os.path.isfile(path):
        return False, f"compile log missing: {path}"
    raw = open(path, "rb").read()
    txt = raw.decode("utf-16", "ignore") if raw[:2] in (b"\xff\xfe", b"\xfe\xff") else raw.decode("utf-8", "ignore")
    import re
    m = re.search(r"(\d+)\s+errors?,\s*(\d+)\s+warnings?", txt, re.I)
    if not m:
        return False, "could not find 'N errors, M warnings' in compile log:\n" + txt[-2000:]
    errs, warns = int(m.group(1)), int(m.group(2))
    return errs == 0, f"compile: {errs} errors, {warns} warnings ({path})"


def cmd_backtest(a):
    validate_args(a)
    term = os.path.abspath(a.terminal_dir)
    terminal = os.path.join(term, "terminal64.exe")
    preset = os.path.abspath(a.preset)
    items = read_set(preset); check_preset_safety(items)
    set_name = os.path.basename(preset)
    stamp = dt.datetime.now().strftime("%Y%m%d_%H%M%S")
    tag = os.path.splitext(set_name)[0]
    report_rel = f"reports\\{tag}_{stamp}"
    ini_path = os.path.join(term, "xau300_runs", f"{tag}_{stamp}.ini")
    ini = build_ini(a, set_name, report_rel)
    cmd = exe_cmd(terminal, ["/portable", f"/config:{to_win_path(ini_path, bool(a.wine))}"], a.wine)
    plan = {"terminal": terminal, "ini_path": ini_path, "ini": ini.split("\r\n"),
            "preset_copy": [preset, os.path.join(term, "MQL5", "Profiles", "Tester", set_name)],
            "ex5_expected": os.path.join(term, "MQL5", "Experts", EA_SUBDIR, EA_NAME + ".ex5"),
            "report_base": os.path.join(term, report_rel.replace("\\", os.sep)), "command": cmd, "timeout_s": a.timeout}
    if a.dry_run:
        print(json.dumps({"dry_run": True, "backtest": plan}, indent=1)); return 0
    if not os.path.isfile(terminal):
        raise RunnerError(f"terminal64.exe not found in {term} (use a dedicated portable install)")
    if not os.path.isfile(plan["ex5_expected"]):
        raise RunnerError("EA not compiled for this terminal: run the 'compile' command first")
    if terminal_running(term):
        raise RunnerError("a terminal from this folder is already running; close it yourself (the runner never kills it)")
    os.makedirs(os.path.dirname(ini_path), exist_ok=True)
    os.makedirs(os.path.dirname(plan["preset_copy"][1]), exist_ok=True)
    os.makedirs(os.path.join(term, "reports"), exist_ok=True)
    shutil.copy2(preset, plan["preset_copy"][1])
    with open(ini_path, "w", encoding="utf-16") as f:     # MT5 reads UTF-16 ini reliably
        f.write(ini)
    t0 = time.time()
    proc = subprocess.Popen(cmd)
    try:
        proc.wait(timeout=a.timeout)
    except subprocess.TimeoutExpired:
        proc.terminate()                                   # only our own child process
        try: proc.wait(30)
        except subprocess.TimeoutExpired: proc.kill()
        raise RunnerError(f"timeout after {a.timeout}s (terminated only the process started by this runner)")
    rep = find_report(plan["report_base"])
    if not rep:
        raise RunnerError(f"no report found at {plan['report_base']}.(htm|html|xml); check {term}/Tester/logs and {term}/logs")
    sys.path.insert(0, HERE)
    import report_parser as RP
    res = RP.parse_report(rep)
    problems = RP.validate(res, expect_symbol=a.symbol, expect_deposit=a.deposit, expect_leverage=a.leverage,
                           expect_model_text=VALID_MODELS.get(a.model))
    res["runner"] = {"seconds": round(time.time() - t0, 1), "ini": ini_path, "report": rep, "preset": dict(items),
                     "tester_log_summary": find_ea_summary(term), "validation_problems": problems}
    out = a.json or os.path.splitext(rep)[0] + ".summary.json"
    json.dump(res, open(out, "w"), indent=1, default=str)
    RP.print_human(res)
    print(f"\nsummary json: {out}")
    if problems:
        print("VALIDATION PROBLEMS:\n - " + "\n - ".join(problems)); return 3
    return 0


def find_report(base):
    for ext in (".htm", ".html", ".xml"):
        if os.path.isfile(base + ext):
            return base + ext
    return None


def find_ea_summary(term):
    """Last 'XAU300|SUMMARY|...' line from tester agent logs (UTF-16 logs)."""
    best = None
    for root, _d, files in os.walk(os.path.join(term, "Tester")):
        for fn in files:
            if not fn.endswith(".log"):
                continue
            p = os.path.join(root, fn)
            try:
                raw = open(p, "rb").read()
                txt = raw.decode("utf-16", "ignore") if raw[:2] in (b"\xff\xfe", b"\xfe\xff") else raw.decode("utf-8", "ignore")
            except Exception:
                continue
            for line in txt.splitlines():
                if "XAU300|SUMMARY|" in line:
                    best = line.split("XAU300|SUMMARY|", 1)[1].strip()
    if not best:
        return None
    return dict(kv.split("=", 1) for kv in best.split() if "=" in kv)


def cmd_parse(a):
    sys.path.insert(0, HERE)
    import report_parser as RP
    res = RP.parse_report(a.report)
    if a.json:
        json.dump(res, open(a.json, "w"), indent=1, default=str)
    RP.print_human(res)
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("compile", "backtest"):
        s = sub.add_parser(name)
        s.add_argument("--terminal-dir", required=True, help="dedicated PORTABLE MT5 folder (contains terminal64.exe)")
        s.add_argument("--wine", default=None, help="wine executable on Linux/macOS (e.g. wine or wine64); omit on Windows")
        s.add_argument("--timeout", type=int, default=3600)
        s.add_argument("--dry-run", action="store_true")
    b = sub.choices["backtest"]
    b.add_argument("--preset", required=True)
    b.add_argument("--symbol", default="XAUUSD")
    b.add_argument("--period", default="M1")
    b.add_argument("--from", dest="date_from", default="2025.10.31")
    b.add_argument("--to", dest="date_to", default="2026.10.31")
    b.add_argument("--model", type=int, default=4)
    b.add_argument("--allow-non-real-ticks", action="store_true")
    b.add_argument("--execution-mode", type=int, default=0, help="0 = no delay; -1 random delay; N ms")
    b.add_argument("--deposit", type=float, default=300.0)
    b.add_argument("--currency", default="USD")
    b.add_argument("--leverage", default="1:500")
    b.add_argument("--json", default=None)
    p = sub.add_parser("parse")
    p.add_argument("--report", required=True)
    p.add_argument("--json", default=None)
    a = ap.parse_args(argv)
    try:
        return {"compile": cmd_compile, "backtest": cmd_backtest, "parse": cmd_parse}[a.cmd](a)
    except RunnerError as e:
        print(f"ERROR: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
